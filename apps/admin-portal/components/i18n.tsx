export type DictionaryKey = keyof typeof dictionaries.en;

function normalizeLocale(value: string | null): Locale {
  return value === 'es' ? 'es' : 'en';
}

export function getStoredLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  return normalizeLocale(window.localStorage.getItem(STORAGE_KEY));
}

export function setStoredLocale(locale: Locale) {
  if (typeof window === 'undefined') return;
  window.localStorage.setItem(STORAGE_KEY, locale);
  window.dispatchEvent(new CustomEvent(LOCALE_EVENT, { detail: locale }));
}

export function useLocale() {
  const [locale, setLocale] = useState<Locale>('en');

  useEffect(() => {
    setLocale(getStoredLocale());
    const handleStorage = () => setLocale(getStoredLocale());
    const handleLocale = (event: Event) => setLocale(normalizeLocale((event as CustomEvent<string>).detail));
    window.addEventListener('storage', handleStorage);
    window.addEventListener(LOCALE_EVENT, handleLocale);
    return () => {
      window.removeEventListener('storage', handleStorage);
      window.removeEventListener(LOCALE_EVENT, handleLocale);
    };
  }, []);

  return locale;
}

export function useTranslation() {
  const locale = useLocale();
  return {
    locale,
    t(key: DictionaryKey) {
      return dictionaries[locale][key] ?? dictionaries.en[key];
    },
  };
}

export function LocalizedText({ k }: { k: DictionaryKey }) {
  const { t } = useTranslation();
  return <>{t(k)}</>;
}

export function RemovedLocaleControl() {
  const locale = useLocale();
  const options: Array<{ locale: Locale; shortLabel: string; label: string }> = [
    { locale: 'en', shortLabel: 'EN', label: dictionaries[locale].english },
    { locale: 'es', shortLabel: 'ES', label: dictionaries[locale].spanish },
  ];

  return (
    <div className="language-switcher" role="group" aria-label={dictionaries[locale].language}>
      {options.map((option) => (
        <button
          key={option.locale}
          type="button"
          className={option.locale === locale ? 'language-flag is-active' : 'language-flag'}
          aria-label={option.label}
          aria-pressed={option.locale === locale}
          title={option.label}
          onClick={() => setStoredLocale(option.locale)}
        >
          <span aria-hidden="true">{option.shortLabel}</span>
        </button>
      ))}
    </div>
  );
}

