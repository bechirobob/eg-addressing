const spanishUiPhraseEntries = Object.entries(spanishUiPhraseMap).sort((a, b) => b[0].length - a[0].length);
const skipSpanishPatchTags = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'CODE', 'PRE', 'TEXTAREA']);
const uiPhraseBoundaryChars = 'A-Za-zÀ-ÖØ-öø-ÿ0-9_';

function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function phraseReplacementPattern(english: string) {
  const startsWithWord = /^[A-Za-z0-9À-ÖØ-öø-ÿ_]/.test(english);
  const endsWithWord = /[A-Za-z0-9À-ÖØ-öø-ÿ_]$/.test(english);
  const prefix = startsWithWord ? `(^|[^${uiPhraseBoundaryChars}])` : '';
  const suffix = endsWithWord ? `(?=$|[^${uiPhraseBoundaryChars}])` : '';
  return new RegExp(`${prefix}(${escapeRegExp(english)})${suffix}`, 'g');
}

function applySpanishUiPhraseMap(value: string) {
  let next = value;
  for (const [english, spanish] of spanishUiPhraseEntries) {
    const pattern = phraseReplacementPattern(english);
    next = next.replace(pattern, (_match, prefix = '') => `${prefix}${spanish}`);
  }
  return next;
}

export function translateUiText(value: string, locale: Locale) {
  return locale === 'es' ? applySpanishUiPhraseMap(value) : value;
}

function patchSpanishTextNodes(root: ParentNode = document.body) {
  if (typeof document === 'undefined') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || skipSpanishPatchTags.has(parent.tagName)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  const nodes: Text[] = [];
  while (walker.nextNode()) {
    nodes.push(walker.currentNode as Text);
  }
  for (const node of nodes) {
    const original = node.nodeValue ?? '';
    if (!original.trim()) continue;
    const next = applySpanishUiPhraseMap(original);
    if (next !== original) node.nodeValue = next;
  }

  const translatableAttrs = ['placeholder', 'aria-label', 'title', 'alt'];
  document.querySelectorAll<HTMLElement>('body *').forEach((element) => {
    if (skipSpanishPatchTags.has(element.tagName)) return;
    translatableAttrs.forEach((attr) => {
      const original = element.getAttribute(attr);
      if (!original?.trim()) return;
      const next = applySpanishUiPhraseMap(original);
      if (next !== original) element.setAttribute(attr, next);
    });
  });
}

export function RemovedSpanishRuntimePatch() {
  const locale = useLocale();
  useEffect(() => {
    if (locale !== 'es') return;
    patchSpanishTextNodes();
    const timers = [50, 250, 750, 1500].map((delay) => window.setTimeout(patchSpanishTextNodes, delay));
    let scheduled = false;
    const schedulePatch = () => {
      if (scheduled) return;
      scheduled = true;
      window.requestAnimationFrame(() => {
        scheduled = false;
        patchSpanishTextNodes();
      });
    };
    const observer = new MutationObserver(schedulePatch);
    observer.observe(document.body, { childList: true, characterData: true, subtree: true });
    return () => {
      timers.forEach((timer) => window.clearTimeout(timer));
      observer.disconnect();
    };
  }, [locale]);
  return null;
}

