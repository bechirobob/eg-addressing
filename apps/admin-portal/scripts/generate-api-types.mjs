import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, '../../..');
const outputPath = resolve(scriptDir, '../components/apiTypes.ts');
const python = resolve(repoRoot, 'services/api/.venv/bin/python');
const code = "import json; from app.main import app; print(json.dumps(app.openapi(), sort_keys=True))";
const result = spawnSync(python, ['-c', code], {
  cwd: resolve(repoRoot, 'services/api'),
  encoding: 'utf8',
});

if (result.status !== 0) {
  process.stderr.write(result.stderr || result.stdout || 'Failed to generate OpenAPI schema.\n');
  process.exit(result.status || 1);
}

const schema = JSON.parse(result.stdout);
const entries = [];
for (const [path, methods] of Object.entries(schema.paths || {})) {
  for (const method of Object.keys(methods)) {
    entries.push({ path, method: method.toUpperCase() });
  }
}
entries.sort((a, b) => `${a.path}:${a.method}`.localeCompare(`${b.path}:${b.method}`));

const pathUnion = [...new Set(entries.map((entry) => JSON.stringify(entry.path)))].join(' | ') || 'never';
const methodUnion = [...new Set(entries.map((entry) => JSON.stringify(entry.method)))].join(' | ') || 'never';
const operationUnion = entries.map((entry) => `{ path: ${JSON.stringify(entry.path)}; method: ${JSON.stringify(entry.method)} }`).join(' |\n  ') || 'never';

const content = `// Generated by scripts/generate-api-types.mjs from FastAPI OpenAPI. Do not edit by hand.\n\nexport type ApiPath = ${pathUnion};\n\nexport type ApiMethod = ${methodUnion};\n\nexport type ApiOperation =\n  ${operationUnion};\n\nexport type PaginatedResponse<T> = {\n  items: T[];\n  pagination?: {\n    page: number;\n    per_page: number;\n    total_items: number;\n    total_pages: number;\n    has_next: boolean;\n    has_previous: boolean;\n  };\n};\n`;

writeFileSync(outputPath, content);
console.log(`Generated ${outputPath} with ${entries.length} API operations.`);
