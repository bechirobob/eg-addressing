import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { chromium } from 'playwright';

const baseUrl = (process.env.OPERATOR_UI_BASE_URL || 'http://127.0.0.1:3100').replace(/\/$/, '');
const outputDir = path.resolve(process.env.OPERATOR_UI_EVIDENCE_DIR || 'artifacts/operator-ui-browser-evidence');
const commitSha = process.env.OPERATOR_UI_COMMIT || process.env.GITHUB_SHA || 'unknown';

await mkdir(outputDir, { recursive: true });

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function userForRole(role) {
  return {
    id: `workspace-${role}`,
    username: `workspace_${role}`,
    full_name: role === 'admin' ? 'National Platform Administrator' : role === 'editor' ? 'Registry Operations Officer' : 'Government Reporting Officer',
    role,
  };
}

async function installSession(page, role) {
  await page.addInitScript(() => {
    window.localStorage.setItem('egAddressingToken', 'workspace-browser-evidence-token');
  });

  await page.route('**/api/v1/auth/me', async (route) => {
    await route.fulfill({
      status: 200,
      contentType: 'application/json',
      body: JSON.stringify({ user: userForRole(role), auth_mode: 'bearer' }),
    });
  });

  await page.route('**/api/v1/auth/logout', async (route) => {
    await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ signed_out: true }) });
  });
}

async function auditWorkspace(browser, { role, viewport, label }) {
  const context = await browser.newContext({ viewport, colorScheme: 'light', reducedMotion: 'reduce' });
  const page = await context.newPage();
  const consoleErrors = [];
  page.on('console', (message) => {
    if (message.type() === 'error') consoleErrors.push(message.text());
  });
  page.on('pageerror', (error) => consoleErrors.push(error.message));

  await installSession(page, role);
  await page.goto(`${baseUrl}/workspace`, { waitUntil: 'domcontentloaded', timeout: 45_000 });
  await page.locator('.government-workspace-root').waitFor({ state: 'visible', timeout: 30_000 });
  await page.locator('.government-coat-of-arms').waitFor({ state: 'visible' });
  await page.waitForTimeout(500);

  const dimensions = await page.evaluate(() => ({
    clientWidth: document.documentElement.clientWidth,
    scrollWidth: document.documentElement.scrollWidth,
    clientHeight: document.documentElement.clientHeight,
    scrollHeight: document.documentElement.scrollHeight,
  }));
  assert(dimensions.scrollWidth <= dimensions.clientWidth + 1, `${label}: body-level horizontal overflow detected`);

  const emblemLoaded = await page.locator('.government-coat-of-arms').evaluate((image) => image instanceof HTMLImageElement && image.complete && image.naturalWidth > 0);
  assert(emblemLoaded, `${label}: official coat of arms did not load`);

  const attribution = await page.locator('.government-delivery-footer').innerText();
  assert(attribution.includes('Developed by BeCoreOps for the Government of the Republic of Equatorial Guinea'), `${label}: approved delivery attribution is missing`);

  const bodyText = await page.locator('body').innerText();
  assert(!/ChatGPT|OpenAI|AI[- ]generated|generated by AI/i.test(bodyText), `${label}: prohibited AI attribution is visible`);
  assert(bodyText.includes('Republic of Equatorial Guinea'), `${label}: government identity is missing`);
  assert(bodyText.includes('National Addressing Platform'), `${label}: platform identity is missing`);

  const visibleNavigationIcons = await page.locator('.government-navigation-link .government-navigation-icon').count();
  if (role === 'admin') {
    assert(visibleNavigationIcons >= 8, `${label}: admin navigation did not expose the expected icon-led workspaces`);
    assert((await page.getByText('Administration', { exact: true }).count()) >= 1, `${label}: admin workspace is missing`);
  } else if (role === 'viewer') {
    assert(visibleNavigationIcons >= 2, `${label}: viewer navigation is incomplete`);
    assert((await page.getByText('Administration', { exact: true }).count()) === 0, `${label}: viewer was shown an admin-only destination`);
  }

  let responsiveMetrics;
  if (viewport.width <= 920) {
    const menu = page.locator('.government-mobile-menu');
    await menu.waitFor({ state: 'visible' });
    await menu.click();
    await page.locator('.government-sidebar.open').waitFor({ state: 'visible' });
    const openSidebarBox = await page.locator('.government-sidebar.open').boundingBox();
    assert(openSidebarBox && openSidebarBox.x >= -1, `${label}: mobile navigation did not enter the viewport`);
    await page.locator('.government-navigation-scrim').click({ position: { x: viewport.width - 10, y: 20 } });
    responsiveMetrics = { mode: 'mobile', menuVisible: true };
  } else {
    const sidebarBox = await page.locator('.government-sidebar').boundingBox();
    const topbarBox = await page.locator('.government-topbar').boundingBox();
    const contentBox = await page.locator('.government-workspace-content').boundingBox();
    assert(sidebarBox && sidebarBox.width >= 220, `${label}: desktop institutional rail is too narrow`);
    assert(topbarBox && topbarBox.width > 700, `${label}: desktop utility bar did not use available width`);
    assert(contentBox && contentBox.width > 700, `${label}: desktop content remains mobile-width`);
    responsiveMetrics = {
      mode: 'desktop',
      sidebarWidth: sidebarBox.width,
      topbarWidth: topbarBox.width,
      contentWidth: contentBox.width,
    };
  }

  const summaryCount = await page.locator('.government-home-summary > div').count();
  assert(summaryCount === 5, `${label}: operational summary must present five stable measures`);
  assert((await page.locator('.government-work-table-row').count()) === 4, `${label}: operational work table is incomplete`);
  assert(consoleErrors.length === 0, `${label}: browser console errors: ${consoleErrors.join(' | ')}`);

  const screenshot = `${label}.png`;
  await page.screenshot({ path: path.join(outputDir, screenshot), fullPage: true });
  await context.close();

  return {
    label,
    role,
    route: '/workspace',
    viewport,
    dimensions,
    responsiveMetrics,
    visibleNavigationIcons,
    screenshot,
    status: 'passed',
  };
}

const browser = await chromium.launch({ headless: true });
try {
  const evidence = [];
  evidence.push(await auditWorkspace(browser, { role: 'admin', viewport: { width: 1440, height: 900 }, label: 'government-workspace-admin-desktop' }));
  evidence.push(await auditWorkspace(browser, { role: 'editor', viewport: { width: 1024, height: 768 }, label: 'government-workspace-editor-tablet' }));
  evidence.push(await auditWorkspace(browser, { role: 'viewer', viewport: { width: 390, height: 844 }, label: 'government-workspace-viewer-mobile' }));

  const result = {
    commitSha,
    generatedAt: new Date().toISOString(),
    baseUrl,
    authorityBoundary: 'Presentation, responsive, branding, and route-visibility evidence only. This is not publication authorization.',
    evidence,
  };
  await writeFile(path.join(outputDir, 'government-workspace-evidence.json'), `${JSON.stringify(result, null, 2)}\n`, 'utf8');
  await writeFile(
    path.join(outputDir, 'government-workspace-README.md'),
    `# Protected government workspace browser audit\n\n- Exact commit: \`${commitSha}\`\n- Desktop, tablet, and mobile audited independently.\n- Official coat of arms loaded in every viewport.\n- BeCoreOps delivery attribution verified.\n- Role-filtered icon navigation verified for administrator and viewer roles.\n- Body-level horizontal overflow: none.\n- AI/ChatGPT attribution: none.\n- Checks passed: ${evidence.length}.\n`,
    'utf8',
  );
  console.log(`government workspace browser audit passed: ${evidence.length} checks`);
} finally {
  await browser.close();
}
